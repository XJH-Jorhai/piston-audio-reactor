import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root=path.resolve(fileURLToPath(new URL('../',import.meta.url))),args=process.argv.slice(2),index=args.indexOf('--source');
if(index<0||!args[index+1])throw Error('Use --source <music-player worktree>.');
const source=await fs.realpath(path.resolve(root,args[index+1]));
const git=(cwd,...values)=>execFileSync('git',values,{cwd,encoding:'utf8'}).trim();
const common=async cwd=>fs.realpath(path.resolve(cwd,git(cwd,'rev-parse','--git-common-dir')));
if(source===root||await common(root)!==await common(source))throw Error('Source must be a separate worktree of this repository.');
if(git(root,'branch','--show-current')!=='main'||git(source,'branch','--show-current')!=='feature/music-player')throw Error('Publish from main using feature/music-player.');
if(git(source,'status','--porcelain'))throw Error('Commit the player source first.');
const commit=git(source,'rev-parse','HEAD'),release=JSON.parse(await fs.readFile(path.join(source,'player/release.json'),'utf8'));
if(release.baseTag!=='v1.0.0'||release.branch!=='feature/music-player')throw Error('Unexpected player release metadata.');
git(source,'merge-base','--is-ancestor','v1.0.0',commit);
if(git(source,'rev-parse','v'+release.version+'^{commit}')!==commit)throw Error('Tag the player source version first.');
if(git(source,'rev-parse','refs/remotes/origin/feature/music-player')!==commit)throw Error('Push the player branch first.');
if(git(root,'status','--porcelain','--','experiments/music-player'))throw Error('The existing player preview has uncommitted changes.');
execFileSync(process.execPath,['scripts/build.mjs'],{cwd:source,stdio:'inherit'});
if(git(source,'rev-parse','HEAD')!==commit||git(source,'status','--porcelain'))throw Error('Source changed during the build.');
const previewRoot=await fs.realpath(path.join(root,'experiments')),target=path.resolve(previewRoot,'music-player');
if(path.dirname(target)!==previewRoot)throw Error('Preview must remain inside experiments/.');
const existing=await fs.lstat(target).catch(error=>{if(error.code==='ENOENT')return null;throw error;});
if(existing?.isSymbolicLink())throw Error('Preview cannot be a symlink.');
if(existing)await fs.rm(target,{recursive:true,force:true});
await fs.cp(path.join(source,'dist/player'),target,{recursive:true});
await fs.writeFile(path.join(target,'preview.json'),JSON.stringify({branch:release.branch,commit,baseTag:release.baseTag,version:release.version,url:'https://xjh-jorhai.github.io/piston-audio-reactor/experiments/music-player/'},null,2)+'\n');
console.log(JSON.stringify({commit,target}));
